// each bit → one of two tones; OfflineAudioContext renders the chirp, a Goertzel demod reads it back.
const F0=1500, F1=2500, BAUD=200, SR=44100; // tones + baud
function fskEncode(bytes){
  const spb=Math.round(SR/BAUD), bits=[]; for(const b of bytes){ for(let i=7;i>=0;i--) bits.push((b>>i)&1); }
  const n=bits.length*spb, buf=new Float32Array(n); let ph=0;
  for(let i=0;i<bits.length;i++){ const f=bits[i]?F1:F0; for(let s=0;s<spb;s++){ ph+=2*Math.PI*f/SR; buf[i*spb+s]=Math.sin(ph)*0.5; } }
  return {buf,spb,nbits:bits.length};
}
function goertzel(buf,start,len,f){ const w=2*Math.PI*f/SR, c=2*Math.cos(w); let s0=0,s1=0,s2=0; for(let i=0;i<len;i++){ s0=buf[start+i]+c*s1-s2; s2=s1; s1=s0; } return s1*s1+s2*s2-c*s1*s2; }
function fskDecode(buf,spb,nbits){
  const bits=[]; for(let i=0;i<nbits;i++){ const st=i*spb; const e0=goertzel(buf,st,spb,F0), e1=goertzel(buf,st,spb,F1); bits.push(e1>e0?1:0); }
  const bytes=new Uint8Array(nbits/8); for(let i=0;i<bytes.length;i++){ let v=0; for(let j=0;j<8;j++) v=(v<<1)|bits[i*8+j]; bytes[i]=v; } return bytes;
}
