// ── Ed25519 helpers (WebCrypto) ────────────────────────────────────────────────────────────
const edOK = (() => { try { return !!(crypto.subtle); } catch { return false; } })();
async function genKeys(){ return crypto.subtle.generateKey({name:'Ed25519'}, true, ['sign','verify']); }
async function edSign(priv,msg){ return new Uint8Array(await crypto.subtle.sign({name:'Ed25519'}, priv, msg)); }
async function edVerify(pub,sig,msg){ try { return await crypto.subtle.verify({name:'Ed25519'}, pub, sig, msg); } catch { return false; } }

// ── WebRTC two-tab demo (BroadcastChannel signaling, STUN only) ──────────────────────────────
const STUN = [{urls:'stun:stun.l.google.com:19302'},{urls:'stun:stun.cloudflare.com:3478'}];
let pc=null, dc=null, myKeys=null, peerPub=null, sourceId=(Math.random()*15|0);
const sig = new BroadcastChannel('fall-airgap-signal');
const rtcState=$('rtc-state'), rtcLog=$('rtc-log');
function setState(s,cls){ rtcState.textContent=s; rtcState.className='pill '+(cls||''); }
function enableSend(on){ ['send-cap','send-hb','send-forge'].forEach(id=>$(id).disabled=!on); }

async function ensureKeys(){ if(!myKeys && edOK){ myKeys=await genKeys(); } }
async function exportPub(k){ return Array.from(new Uint8Array(await crypto.subtle.exportKey('raw',k))); }
async function importPub(arr){ return crypto.subtle.importKey('raw',new Uint8Array(arr),{name:'Ed25519'},true,['verify']); }

function wireDC(channel){
  dc=channel;
  dc.binaryType='arraybuffer';
  dc.onopen=async()=>{ setState('connected','ok'); enableSend(true); if(edOK){ sig.postMessage({t:'pub', from:sourceId, pub:await exportPub(myKeys.publicKey)}); } };
  dc.onclose=()=>{ setState('closed','warn'); enableSend(false); };
  dc.onmessage=async(ev)=>{
    const raw=new Uint8Array(ev.data);
    // SIGNATURE FIRST: verify before the payload is parsed
    const res=K.sigFirstDrop(raw, (pub,msg,s)=>false, null); // sync fallback never used; real verify below
    if(!peerPub && !edOK){ log(rtcLog,'⚠ WebCrypto Ed25519 unavailable in this browser — cannot verify'); return; }
    const sigBytes=raw.subarray(1+K.PAYLOAD), msg=raw.subarray(0,1+K.PAYLOAD);
    const good = peerPub ? await edVerify(peerPub, sigBytes, msg) : false;
    if(!good){ log(rtcLog,'✗ DROPPED before parse — signature did not map (forged/tampered). The unverified command never compiled.'); return; }
    const payload=raw.subarray(1,1+K.PAYLOAD);
    const dec=K.decodeEvent(payload);
    const json=K.canonicalJson(dec);
    log(rtcLog,'✓ verified → '+dec.type+'  ['+Array.from(payload).join(',')+']  6B vs '+K.utf8Bytes(json)+'B JSON');
  };
}

